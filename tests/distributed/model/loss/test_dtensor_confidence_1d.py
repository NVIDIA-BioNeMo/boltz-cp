def _worker_compute_frame_pred_1d(rank, payload):
    """Worker: _compute_frame_pred_1d parity with serial compute_frame_pred."""
    (
        grid_group_sizes,
        device_type,
        backend,
        env_per_rank,
        multiplicity,
        pred_atom_coords_host,
        feats_host,
        expected_frames_idx_host,
        expected_mask_collinear_host,
    ) = payload

    monkeypatch = pytest.MonkeyPatch()
    if env_per_rank is not None:
        for var_name, value in env_per_rank.items():
            if value == "<INPUT_RANK>":
                monkeypatch.setenv(var_name, f"{rank}")
                continue
            monkeypatch.setenv(var_name, value)

    DistributedManager.initialize(grid_group_sizes, device_type=device_type, backend=backend)
    dm = DistributedManager()
    device_mesh = dm.device_mesh
    device = dm.device

    # Distribute atom coords: [B*mult, N_atom, 3] -> atom placement (Shard(0), Replicate())
    pred_coords_dt = distribute_tensor(pred_atom_coords_host.to(device), device_mesh, _ATOM)
    # Distribute frames_idx: [B, N_token, 3] -> single placement (Shard(0), Shard(1))
    frames_idx_dt = distribute_tensor(feats_host["frames_idx"].to(device), device_mesh, _SINGLE)
    feats_dt = _distribute_feats_1d(feats_host, device_mesh, device)

    frames_idx_pred, mask_collinear_pred = _compute_frame_pred_1d(
        pred_atom_coords=pred_coords_dt,
        frames_idx_true=frames_idx_dt,
        feats=feats_dt,
        multiplicity=multiplicity,
        device_mesh=device_mesh,
    )

    # --- Compare frames_idx_pred via geometry proxy ---
    # _compute_frame_pred_1d returns [B, mult, N, 3] with (Shard(0), Shard(2))
    # Gather to full for comparison
    size_batch = feats_host["atom_pad_mask"].shape[0]
    _, num_tokens = feats_host["asym_id"].shape

    replicate_pl = (Replicate(), Replicate())
    frames_idx_pred_full = frames_idx_pred.redistribute(device_mesh, placements=replicate_pl).to_local()

    pred_coords_local = pred_atom_coords_host.to(device).unflatten(0, (size_batch, multiplicity))
    expected_frames_idx_local = expected_frames_idx_host.to(device)

    batch_idx = torch.arange(size_batch, device=device)[:, None, None, None]
    mult_idx = torch.arange(multiplicity, device=device)[None, :, None, None]

    dt_frames = pred_coords_local[batch_idx, mult_idx, frames_idx_pred_full]
    host_frames = pred_coords_local[batch_idx, mult_idx, expected_frames_idx_local]

    # Use mean frame center as an index-invariant proxy
    dt_frame_centers = dt_frames.mean(dim=-2)
    host_frame_centers = host_frames.mean(dim=-2)

    token_pad_mask_bool = feats_host["token_pad_mask"].bool().to(device)
    for batch_i in range(size_batch):
        valid = token_pad_mask_bool[batch_i]
        assert valid.any(), f"batch {batch_i} has no valid tokens"
        torch.testing.assert_close(
            dt_frame_centers[batch_i, :, valid].cpu(),
            host_frame_centers[batch_i, :, valid].cpu(),
            msg=lambda m: f"Rank {rank} frames_idx_pred mismatch\n{m}",
        )

    # --- Compare mask_collinear ---
    mask_collinear_full = mask_collinear_pred.full_tensor().cpu()
    expected_mask_cpu = expected_mask_collinear_host.cpu()

    for batch_i in range(mask_collinear_full.shape[0]):
        valid = feats_host["token_pad_mask"][batch_i].bool()
        actual_valid = mask_collinear_full[batch_i, :, valid]
        expected_valid = expected_mask_cpu[batch_i, :, valid]

        # Non-vacuous: at least some collinear entries on valid tokens
        assert actual_valid.any() or expected_valid.any(), (
            f"batch {batch_i} mask_collinear on valid tokens is always False for both "
            "actual and expected — test is vacuous"
        )

        torch.testing.assert_close(
            actual_valid,
            expected_valid,
            msg=lambda m: f"Rank {rank} mask_collinear mismatch batch {batch_i}\n{m}",
        )

    DistributedManager.cleanup()
    monkeypatch.undo()


def _worker_resolved_loss_1d(rank, payload):
    """Worker: resolved_loss_1d parity with serial."""
    (
        grid_group_sizes,
        device_type,
        backend,
        env_per_rank,
        pred_resolved_host,
        feats_host,
        true_coords_resolved_mask_host,
        expected_loss,
        expected_pred_grad,
        d_loss_host,
        multiplicity,
        atom_pl,
    ) = payload

    monkeypatch = pytest.MonkeyPatch()
    if env_per_rank is not None:
        for var_name, value in env_per_rank.items():
            if value == "<INPUT_RANK>":
                monkeypatch.setenv(var_name, f"{rank}")
                continue
            monkeypatch.setenv(var_name, value)

    DistributedManager.initialize(grid_group_sizes, device_type=device_type, backend=backend)
    dm = DistributedManager()
    device_mesh = dm.device_mesh
    device = dm.device

    pred_dt = distribute_tensor(pred_resolved_host.to(device), device_mesh, _SINGLE).requires_grad_(True)
    mask_dt = distribute_tensor(true_coords_resolved_mask_host.to(device), device_mesh, atom_pl)
    feats_dt = _distribute_feats_1d(feats_host, device_mesh, device, atom_pl=atom_pl)

    dp_group = device_mesh.get_group("dp")
    cp_group = device_mesh.get_group("cp")

    loss_dt = resolved_loss_1d(
        pred_resolved=pred_dt,
        feats=feats_dt,
        true_coords_resolved_mask=mask_dt,
        device_mesh=device_mesh,
        dp_group=dp_group,
        cp_group=cp_group,
        multiplicity=multiplicity,
    )

    # Forward parity
    loss_val = loss_dt.full_tensor().item()
    # fp32 defaults: per-element BCE mean reduction (N=B*n_tokens*2 ~144) with one packed all_reduce; no cp-reorder.
    torch.testing.assert_close(
        torch.tensor(loss_val),
        torch.tensor(expected_loss),
        msg=lambda m: f"Rank {rank} resolved loss mismatch\n{m}",
    )

    # Backward
    d_loss_dt = distribute_tensor(d_loss_host.to(device), device_mesh, _REPLICATED)
    loss_dt.backward(d_loss_dt)

    assert pred_dt.grad is not None, "pred gradient is None"
    pred_grad_full = pred_dt.grad.full_tensor()
    # fp32 defaults: per-element BCE backward (identity through all_reduce); no cp-reorder, single packed all_reduce.
    torch.testing.assert_close(
        pred_grad_full.cpu(),
        expected_pred_grad,
        msg=lambda m: f"Rank {rank} resolved grad mismatch\n{m}",
    )

    # Non-vacuous
    assert pred_grad_full.abs().sum() > 0, "Gradient is all-zero"

    DistributedManager.cleanup()
    monkeypatch.undo()


def _worker_plddt_loss_1d(rank, payload):
    """Worker: plddt_loss_1d parity with serial."""
    (
        grid_group_sizes,
        device_type,
        backend,
        env_per_rank,
        pred_lddt_host,
        pred_atom_coords_host,
        true_atom_coords_host,
        true_coords_resolved_mask_host,
        feats_host,
        expected_loss,
        expected_pred_grad,
        d_loss_host,
        multiplicity,
        atom_pl,
    ) = payload

    monkeypatch = pytest.MonkeyPatch()
    if env_per_rank is not None:
        for var_name, value in env_per_rank.items():
            if value == "<INPUT_RANK>":
                monkeypatch.setenv(var_name, f"{rank}")
                continue
            monkeypatch.setenv(var_name, value)

    DistributedManager.initialize(grid_group_sizes, device_type=device_type, backend=backend)
    dm = DistributedManager()
    device_mesh = dm.device_mesh
    device = dm.device

    pred_dt = distribute_tensor(pred_lddt_host.to(device), device_mesh, _SINGLE).requires_grad_(True)
    pred_coords_dt = distribute_tensor(pred_atom_coords_host.to(device), device_mesh, atom_pl)
    true_coords_dt = distribute_tensor(true_atom_coords_host.to(device), device_mesh, atom_pl)
    mask_dt = distribute_tensor(true_coords_resolved_mask_host.to(device), device_mesh, atom_pl)
    feats_dt = _distribute_feats_1d(feats_host, device_mesh, device, atom_pl=atom_pl)

    dp_group = device_mesh.get_group("dp")
    cp_group = device_mesh.get_group("cp")

    loss_dt = plddt_loss_1d(
        pred_lddt=pred_dt,
        pred_atom_coords=pred_coords_dt,
        true_atom_coords=true_coords_dt,
        true_coords_resolved_mask=mask_dt,
        feats=feats_dt,
        device_mesh=device_mesh,
        dp_group=dp_group,
        cp_group=cp_group,
        multiplicity=multiplicity,
    )

    # Forward parity
    # pLDDT loss uses floor(target_lddt * num_bins) to quantize into bins.
    # With cp>1, all-reduce ordering differences cause O(eps) shifts in
    # target_lddt, which can move it across a bin boundary.  The resulting
    # one-hot target changes discretely, producing O(1/num_bins) ~ 0.02
    # absolute loss error.  We relax tolerance accordingly for cp>1.
    cp_size = grid_group_sizes["cp"]
    loss_atol = 0.01 if cp_size > 1 else 1e-4
    loss_rtol = 0.01 if cp_size > 1 else 1e-4
    loss_val = loss_dt.full_tensor().item()
    torch.testing.assert_close(
        torch.tensor(loss_val),
        torch.tensor(expected_loss),
        atol=loss_atol,
        rtol=loss_rtol,
        msg=lambda m: f"Rank {rank} plddt loss mismatch\n{m}",
    )

    # Backward
    # Grad tolerance relaxed for cp>1: bin quantization sensitivity in the
    # forward propagates through cross-entropy backward into logit gradients.
    grad_atol = 0.02 if cp_size > 1 else 5e-4
    grad_rtol = 0.02 if cp_size > 1 else 5e-4
    d_loss_dt = distribute_tensor(d_loss_host.to(device), device_mesh, _REPLICATED)
    loss_dt.backward(d_loss_dt)

    assert pred_dt.grad is not None, "pred gradient is None"
    pred_grad_full = pred_dt.grad.full_tensor()
    torch.testing.assert_close(
        pred_grad_full.cpu(),
        expected_pred_grad,
        atol=grad_atol,
        rtol=grad_rtol,
        msg=lambda m: f"Rank {rank} plddt grad mismatch\n{m}",
    )

    # Non-vacuous
    assert pred_grad_full.abs().sum() > 0, "Gradient is all-zero"

    DistributedManager.cleanup()
    monkeypatch.undo()


