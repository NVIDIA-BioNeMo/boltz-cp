def _inject_cross_shard_self_pairs(feats: dict, cp_size: int) -> dict:
    """Mutate ``r_set_to_rep_atom`` to install cross-shard self-pairs that
    the buggy intra-shard mask cannot catch.

    For every rank-0-local token ``t`` (i.e. ``t in [0, n_tokens // cp)``),
    we install one R-set entry on each higher-rank shard whose rep_atom
    matches token ``t``'s rep_atom. Specifically: for cp-rank ``r >= 1``,
    we override R-set entries
    ``r * (N_R // cp) .. r * (N_R // cp) + tokens_per_rank`` so each one
    points to a distinct rank-0 token's rep_atom. After distribution under
    (Shard(0), Shard(1)) those entries land on cp-rank ``r``, while the
    matching tokens live on cp-rank 0 — so every (token, R-set entry)
    match in this injected block is a cross-shard self-pair.

    The serial loss zeros all such pairs via
    ``pair_mask = pair_mask * (1 - eye)`` then projection through
    ``r_set_to_rep_atom``; the buggy distributed loss leaves them unmasked
    because it only zeros the intra-shard slice
    ``pair_mask[:, :, shard_start:shard_end]``.

    Because the injected rep_atom matches the LOCAL token's rep_atom on
    rank 0, the cdist contribution at that pair is exactly zero and the
    score saturates at 1.0 — so each unmasked injection adds 1 to both
    ``out_num`` and ``out_denom`` for the affected token, biasing
    ``target_lddt`` by ~1 / (out_denom + 1). With ``tokens_per_rank``
    injections per affected token across (cp-1) ranks, the bias is large
    enough to cross multiple ``floor(target_lddt * num_bins)`` boundaries
    and shift the cross-entropy loss far beyond the 0.01 atol budget.

    Returns
    -------
    dict
        The mutated ``feats`` (modified in place) — convenient for chaining.
    """
    t2ra = feats["token_to_rep_atom"]
    r2ra = feats["r_set_to_rep_atom"]
    n_tokens_total = t2ra.shape[1]
    n_r = r2ra.shape[1]
    tokens_per_rank = n_tokens_total // cp_size
    r_per_rank = n_r // cp_size

    # rank-0-local token indices: 0 .. tokens_per_rank - 1
    # Each gets one injected R-set entry per higher rank.
    rank0_token_idx = torch.arange(tokens_per_rank)
    rank0_rep_atoms = t2ra[:, rank0_token_idx, :].argmax(dim=-1)  # [B, tokens_per_rank]

    # Number of slots we can inject per non-zero rank: min(tokens_per_rank, r_per_rank).
    # In practice tokens_per_rank == n_tokens // cp_size and r_per_rank <= n_tokens // cp_size,
    # so we cap at r_per_rank.
    n_inject = min(tokens_per_rank, r_per_rank)

    for r in range(1, cp_size):
        base = r * r_per_rank
        # Override entries [base : base + n_inject] to point at rank-0 tokens' rep_atoms.
        r2ra[:, base : base + n_inject, :] = 0
        for j in range(n_inject):
            for b in range(r2ra.shape[0]):
                r2ra[b, base + j, rank0_rep_atoms[b, j]] = 1.0

    feats["token_to_rep_atom"] = t2ra
    feats["r_set_to_rep_atom"] = r2ra
    return feats


