"""DTensor-based tests for 1D CP confidence loss.

Tests the 1D CP confidence loss sub-functions (resolved_loss_1d, plddt_loss_1d,
pde_loss_1d, pae_loss_1d) and the top-level aggregator (confidence_loss_1d)
against their serial equivalents from boltz.model.loss.confidencev2.

Maps to: src/boltz/distributed/model/loss/confidence_1d.py

Test strategy:
  - Generate random features on CPU using ``random_features``.
  - Compute serial loss + gradient as reference.
  - Distribute features to the 2D mesh (dp, cp) with 1D CP placements.
  - Compute distributed loss + gradient.
  - Assert forward parity (loss value), backward parity (pred gradient),
    non-vacuousness (non-zero gradients), and immutability (inputs unchanged).
"""

import pytest
import torch
from torch.distributed.tensor import Replicate, Shard, distribute_tensor

from boltz.distributed.manager import DistributedManager
